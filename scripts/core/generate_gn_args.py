#!/usr/bin/env python3
"""
Cerium Declarative GN Arguments Generator
(scripts/core/generate-gn-args.py)

Combines declarative GN configurations from configs/gn/ into target args.gn:
- configs/gn/common.gni
- configs/gn/<platform>.gni
- configs/gn/debloat.gni
Substituting build-specific variables (${TARGET_ARCH}, ${PACKAGE_ID}, ${BRAVE_VERSION}).
"""

import argparse
import os
import sys


def generate_gn_args(
    repo_root: str,
    platform: str,
    arch: str,
    version: str = "",
    package_id: str = "",
    out_file: str = "",
) -> str:
    configs_dir = os.path.join(repo_root, "configs", "gn")
    platform_file = os.path.join(configs_dir, f"{platform}.gni")
    common_file = os.path.join(configs_dir, "common.gni")
    debloat_file = os.path.join(configs_dir, "debloat.gni")

    if not os.path.isfile(platform_file):
        raise FileNotFoundError(f"Missing platform GN config: {platform_file}")
    if not os.path.isfile(common_file):
        raise FileNotFoundError(f"Missing common GN config: {common_file}")
    if not os.path.isfile(debloat_file):
        raise FileNotFoundError(f"Missing debloat GN config: {debloat_file}")

    with open(platform_file, "r", encoding="utf-8") as f:
        platform_content = f.read()
    with open(common_file, "r", encoding="utf-8") as f:
        common_content = f.read()
    with open(debloat_file, "r", encoding="utf-8") as f:
        debloat_content = f.read()

    combined = (
        f"# Automatically generated by generate-gn-args.py for {platform} ({arch})\n"
        f"# DO NOT EDIT DIRECTLY. Edit configs/gn/*.gni instead.\n\n"
        f"{platform_content.strip()}\n\n"
        f"# Common Base Configuration\n"
        f"{common_content.strip()}\n\n"
        f"# Debloated Services & Telemetry Suppression\n"
        f"{debloat_content.strip()}\n"
    )

    replacements = {
        "${TARGET_ARCH}": arch,
        "${PACKAGE_ID}": package_id,
        "${BRAVE_VERSION}": version,
    }
    for var, val in replacements.items():
        combined = combined.replace(var, val)

    if out_file:
        os.makedirs(os.path.dirname(os.path.abspath(out_file)), exist_ok=True)
        with open(out_file, "w", encoding="utf-8") as f:
            f.write(combined)

    return combined


def main():
    parser = argparse.ArgumentParser(description="Generate Cerium args.gn")
    parser.add_argument("--repo-root", default="", help="Path to Cerium repository root")
    parser.add_argument("--platform", required=True, choices=["android", "windows"], help="Target platform")
    parser.add_argument("--arch", required=True, help="Target CPU architecture (e.g. arm64, x64)")
    parser.add_argument("--version", default="", help="Release version (e.g. 1.99.55)")
    parser.add_argument("--package-id", default="", help="Android package ID (e.g. org.ceriumbrowser.cerium)")
    parser.add_argument("--out", default="", help="Path to write generated args.gn")

    args = parser.parse_args()
    repo_root = args.repo_root or os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))

    result = generate_gn_args(
        repo_root=repo_root,
        platform=args.platform,
        arch=args.arch,
        version=args.version,
        package_id=args.package_id,
        out_file=args.out,
    )
    if not args.out:
        print(result)


if __name__ == "__main__":
    main()
